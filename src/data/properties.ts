export function formatRent(rent: number): string {
  if (rent >= 100000) {
    return `${(rent / 100000).toFixed(1)}L`;
  }
  if (rent >= 1000) {
    return `${(rent / 1000).toFixed(0)}K`;
  }
  return rent.toString();
}

export function getPropertyBadge(property: Property): string | null {
  if (property.isFeatured) return 'Featured';
  if (property.isVerified) return 'Verified';
  return null;
}